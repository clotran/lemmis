C     DATALATE: DATA STATEMENTS AFTER STATEMENT FUNCTIONS AND AFTER
C     EXECUTABLE STATEMENTS (F77 3.5, 9.1): THE VALUES ARE INITIAL
      PROGRAM DATALATE
      INTEGER K, L(3)
      F(X) = X + 1.0
      DATA K /3/
      WRITE (6, 1) K, F(1.0)
    1 FORMAT (1X, I2, F5.1)
      K = 5
      DATA L / 1, 2*7 /
      WRITE (6, 2) K, L
    2 FORMAT (1X, 4I3)
      END
