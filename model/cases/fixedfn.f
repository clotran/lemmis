C     FIXEDFN: TYPED FUNCTION HEADERS IN FIXED FORM, BLANKS OPTIONAL
C     (F77 3.1.6, 15.5.1): COMPLEX FUNCTION, CHARACTER*LEN FUNCTION,
C     CHARACTER*(*) FUNCTION, CHARACTER*(LEN) DECLARATIONS
      PROGRAM FIXEDFN
      COMPLEX ZF, Z
      CHARACTER CF*10, CG*4, C*10, D*4
      CHARACTER*(3) E
      Z = ZF(1.0, 2.0)
      C = CF(2)
      D = CG('WXYZ')
      E = 'PQR'
      WRITE (6, 1) REAL(Z), AIMAG(Z), C, D, E
    1 FORMAT (1X, 2F5.1, 1X, A, 1X, A, 1X, A)
      END
      COMPLEXFUNCTION ZF(A, B)
      ZF = CMPLX(A, B)
      END
      CHARACTER*10 FUNCTION CF(I)
      CF = 'ABC'
      IF (I .GT. 1) CF = 'DEFG'
      END
      CHARACTER*(*)FUNCTION CG(S)
      CHARACTER*(*) S
      CG = S
      END
