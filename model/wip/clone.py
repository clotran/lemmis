#!/usr/bin/env python3
# clone.py MAPFILE SRC DST [include-line...]: copy the top-level events of SRC
# that mention a renamed symbol (transitively), renaming every symbol they
# define; drop the rest (the original book is included). MAPFILE (json)
# holds the renames so far and is updated.
import json, re, sys

mapfile, src, dst = sys.argv[1:4]
extra_inc = sys.argv[4:]
ren = json.load(open(mapfile))
text = open(src).read()

def forms(t):
    out, i, n = [], 0, len(t)
    while i < n:
        c = t[i]
        if c == ';':
            j = t.find('\n', i); j = n if j < 0 else j
            out.append(('c', t[i:j])); i = j
        elif c == '#' and t.startswith('#|', i):
            j = t.find('|#', i) + 2; out.append(('c', t[i:j])); i = j
        elif c == '(':
            d, j = 0, i
            while True:
                ch = t[j]
                if ch == '"':
                    j += 1
                    while t[j] != '"':
                        j += 2 if t[j] == '\\' else 1
                elif ch == ';':
                    j = t.find('\n', j) - 1
                elif ch == '#' and t.startswith('#\\', j):
                    j += 2
                elif ch == '(':
                    d += 1
                elif ch == ')':
                    d -= 1
                    if d == 0:
                        break
                j += 1
            out.append(('f', t[i:j+1])); i = j + 1
        else:
            out.append(('w', c)); i += 1
    return out

TOK = re.compile(r'[^\s()\'`,";|]+')
def toks(f):
    # strip strings and comments
    s = re.sub(r'"(\\.|[^"\\])*"', '""', f)
    s = re.sub(r';[^\n]*', '', s)
    return set(t.lower() for t in TOK.findall(s))

DEF = re.compile(r'\((?:defthm|defthmd|defun|defund|defun-sk|defmacro|defconst|defun-nx|defabbrev)\s+([^\s()]+)', re.I)
def defined(f):
    return [m.lower() for m in DEF.findall(f)]

fs = forms(text)
keep = [False] * len(fs)
changed = True
while changed:
    changed = False
    for k, (kind, f) in enumerate(fs):
        if kind != 'f' or keep[k]:
            continue
        head = f[1:20].lower()
        if head.startswith('include-book') or head.startswith('in-package'):
            continue
        if toks(f) & set(ren):
            keep[k] = True; changed = True
            for d in defined(f):
                if d not in ren:
                    ren[d] = d + '-f'

def rename(f):
    def sub(m):
        t = m.group(0)
        return ren.get(t.lower(), t)
    # rename symbols outside strings/comments
    parts = re.split(r'("(?:\\.|[^"\\])*"|;[^\n]*)', f)
    return ''.join(p if (p.startswith('"') or p.startswith(';')) else TOK.sub(sub, p) for p in parts)

out = ['; generated by clone.py from %s: its events reading sv/sx/a-sx, on svf/sxf/a-sxf\n' % src,
       '(in-package "ACL2")\n']
for inc in extra_inc:
    out.append('(include-book "%s")\n' % inc)
for k, (kind, f) in enumerate(fs):
    if keep[k]:
        out.append('\n' + rename(f) + '\n')
open(dst, 'w').write(''.join(out))
json.dump(ren, open(mapfile, 'w'), indent=0)
print(dst, sum(keep), 'events kept of', sum(1 for x in fs if x[0] == 'f'))
